import { SEVERITIES, getCheck } from '../data/demo'
import {
  findingsFor,
  formatDate,
  formatDuration,
  summarize,
} from './scans'
import { hostnameOf } from './url'

function severityLabel(severity) {
  return SEVERITIES[severity]?.label ?? severity
}

export function buildMarkdownReport(scan) {
  const summary = summarize(scan)
  const findings = findingsFor(scan)
  const host = hostnameOf(scan.target)

  const lines = [
    '# WebAuditors — Demonstration Security Report',
    '',
    '> **DEMO DATA — No live security scan was performed.**',
    '> All findings in this report are simulated for product demonstration.',
    '> Do not treat them as results for a real website.',
    '',
    `- **Target:** ${scan.target}`,
    `- **Scan date:** ${formatDate(scan.startedAt)}`,
    `- **Duration:** ${formatDuration(scan.durationMs)} (simulated)`,
    `- **Checks completed:** ${scan.checks.length}`,
    `- **Overall status:** ${summary.status} (${summary.high} high, ${summary.medium} medium, ${summary.info} informational)`,
    '',
    '> The overall status summarises the simulated findings below. It is not a',
    '> security score and does not guarantee that the website is secure or insecure.',
    '',
    '## Findings',
    '',
  ]

  if (findings.length === 0) {
    lines.push('No findings in this demonstration report.', '')
  }

  findings.forEach((finding, index) => {
    const check = getCheck(finding.checkId)
    lines.push(
      `### ${index + 1}. [${severityLabel(finding.severity)}] ${finding.title}`,
      '',
      `- **Category:** ${finding.category}`,
      `- **Check:** ${check?.name ?? finding.checkId}`,
      `- **Type:** ${finding.kind}`,
      `- **Confidence:** ${finding.confidence}`,
      '',
      '**What was detected**',
      '',
      finding.description,
      '',
      '**Demonstration evidence**',
      '',
      '```',
      finding.evidence,
      '```',
      '',
      `_${finding.evidenceNote}_`,
      '',
      '**Why it matters**',
      '',
      finding.why,
      '',
      '**Potential impact**',
      '',
      finding.impact,
      '',
      '**Recommended fix**',
      '',
      finding.recommendation,
      '',
      '**How to verify the fix**',
      '',
      ...finding.verification.map((step) => `1. ${step}`),
      '',
      '**Limitations and possible false positives**',
      '',
      finding.limitations,
      '',
      '---',
      '',
    )
  })

  lines.push(
    '## About this report',
    '',
    '- Generated by the WebAuditors interactive prototype.',
    '- No HTTP requests, scans, exploits or credential checks were performed.',
    '- Simulated results cannot confirm that a website is secure or insecure.',
    `- Report prepared for ${host}.`,
    '',
    'WebAuditors — demonstration export',
  )

  return lines.join('\n')
}

export function reportFilename(scan) {
  const host = hostnameOf(scan.target).replace(/[^a-z0-9.-]/gi, '-')
  const date = new Date(scan.startedAt).toISOString().slice(0, 10)
  return `webauditors-demo-report-${host}-${date}.md`
}

export function downloadReport(scan) {
  const markdown = buildMarkdownReport(scan)
  const blob = new Blob([markdown], { type: 'text/markdown;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = reportFilename(scan)
  document.body.appendChild(link)
  link.click()
  link.remove()
  URL.revokeObjectURL(url)
}
